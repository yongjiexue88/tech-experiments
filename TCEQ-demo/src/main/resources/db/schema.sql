-- ── Sequences (Oracle-style) ─────────────────────────────────
CREATE SEQUENCE FACILITY_SEQ    START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE PERMIT_SEQ      START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE INSPECTION_SEQ  START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE VIOLATION_SEQ   START WITH 1 INCREMENT BY 1;

-- ── Facilities Table ─────────────────────────────────────────
CREATE TABLE FACILITIES (
    ID                NUMBER(19)     DEFAULT FACILITY_SEQ.NEXTVAL PRIMARY KEY,
    FACILITY_NAME     VARCHAR2(200)  NOT NULL,
    EPA_ID            VARCHAR2(20)   NOT NULL,
    FACILITY_TYPE     VARCHAR2(50),
    ADDRESS           VARCHAR2(300),
    CITY              VARCHAR2(100),
    COUNTY            VARCHAR2(100),
    STATE_CODE        VARCHAR2(2)    DEFAULT 'TX',
    ZIP_CODE          VARCHAR2(10),
    LATITUDE          NUMBER(10,7),
    LONGITUDE         NUMBER(11,7),
    STATUS            VARCHAR2(20)   DEFAULT 'ACTIVE',
    REGISTRATION_DATE DATE,
    CONSTRAINT UK_FACILITY_EPA_ID UNIQUE (EPA_ID),
    CONSTRAINT CHK_FACILITY_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED','CLOSED'))
);

CREATE INDEX IDX_FACILITY_EPA_ID  ON FACILITIES (EPA_ID);
CREATE INDEX IDX_FACILITY_COUNTY  ON FACILITIES (COUNTY);
CREATE INDEX IDX_FACILITY_TYPE    ON FACILITIES (FACILITY_TYPE);
CREATE INDEX IDX_FACILITY_STATUS  ON FACILITIES (STATUS);

-- ── Permits Table ────────────────────────────────────────────
CREATE TABLE PERMITS (
    ID              NUMBER(19)     DEFAULT PERMIT_SEQ.NEXTVAL PRIMARY KEY,
    PERMIT_NUMBER   VARCHAR2(30)   NOT NULL,
    PERMIT_TYPE     VARCHAR2(50),
    ISSUE_DATE      DATE,
    EXPIRY_DATE     DATE,
    STATUS          VARCHAR2(20)   DEFAULT 'ACTIVE',
    DESCRIPTION     VARCHAR2(500),
    FACILITY_ID     NUMBER(19)     NOT NULL,
    CONSTRAINT UK_PERMIT_NUMBER UNIQUE (PERMIT_NUMBER),
    CONSTRAINT FK_PERMIT_FACILITY FOREIGN KEY (FACILITY_ID)
        REFERENCES FACILITIES (ID) ON DELETE CASCADE,
    CONSTRAINT CHK_PERMIT_STATUS CHECK (STATUS IN ('ACTIVE','EXPIRED','REVOKED','PENDING'))
);

CREATE INDEX IDX_PERMIT_NUMBER    ON PERMITS (PERMIT_NUMBER);
CREATE INDEX IDX_PERMIT_STATUS    ON PERMITS (STATUS);
CREATE INDEX IDX_PERMIT_FACILITY  ON PERMITS (FACILITY_ID);

-- ── Inspections Table ────────────────────────────────────────
CREATE TABLE INSPECTIONS (
    ID                   NUMBER(19)     DEFAULT INSPECTION_SEQ.NEXTVAL PRIMARY KEY,
    INSPECTION_DATE      DATE           NOT NULL,
    INSPECTION_TYPE      VARCHAR2(30),
    INSPECTOR_NAME       VARCHAR2(100)  NOT NULL,
    FINDINGS             VARCHAR2(1000),
    RESULT               VARCHAR2(20),
    NEXT_INSPECTION_DUE  DATE,
    FACILITY_ID          NUMBER(19)     NOT NULL,
    CONSTRAINT FK_INSPECTION_FACILITY FOREIGN KEY (FACILITY_ID)
        REFERENCES FACILITIES (ID) ON DELETE CASCADE,
    CONSTRAINT CHK_INSPECTION_RESULT CHECK (RESULT IN ('PASS','FAIL','PENDING','FOLLOW_UP'))
);

CREATE INDEX IDX_INSPECTION_DATE     ON INSPECTIONS (INSPECTION_DATE);
CREATE INDEX IDX_INSPECTION_RESULT   ON INSPECTIONS (RESULT);
CREATE INDEX IDX_INSPECTION_FACILITY ON INSPECTIONS (FACILITY_ID);

-- ── Violations Table ─────────────────────────────────────────
CREATE TABLE VIOLATIONS (
    ID                NUMBER(19)     DEFAULT VIOLATION_SEQ.NEXTVAL PRIMARY KEY,
    VIOLATION_CODE    VARCHAR2(30)   NOT NULL,
    DESCRIPTION       VARCHAR2(500),
    SEVERITY          VARCHAR2(20),
    VIOLATION_DATE    DATE,
    STATUS            VARCHAR2(20)   DEFAULT 'OPEN',
    CORRECTIVE_ACTION VARCHAR2(500),
    PENALTY_AMOUNT    NUMBER(12,2)   DEFAULT 0,
    RESOLUTION_DATE   DATE,
    FACILITY_ID       NUMBER(19)     NOT NULL,
    CONSTRAINT FK_VIOLATION_FACILITY FOREIGN KEY (FACILITY_ID)
        REFERENCES FACILITIES (ID) ON DELETE CASCADE,
    CONSTRAINT CHK_VIOLATION_SEVERITY CHECK (SEVERITY IN ('MINOR','MAJOR','CRITICAL')),
    CONSTRAINT CHK_VIOLATION_STATUS   CHECK (STATUS IN ('OPEN','RESOLVED','APPEALED','CLOSED'))
);

CREATE INDEX IDX_VIOLATION_SEVERITY  ON VIOLATIONS (SEVERITY);
CREATE INDEX IDX_VIOLATION_STATUS    ON VIOLATIONS (STATUS);
CREATE INDEX IDX_VIOLATION_FACILITY  ON VIOLATIONS (FACILITY_ID);

